import { Outlet, useNavigate, useLocation } from 'react-router-dom'
import { useSettings } from '../contexts/SettingsContext'
import { useEffect } from 'react'

const NAV = [
  { path: '/', label: 'Today', icon: HomeIcon },
  { path: '/log', label: 'Log', icon: LogIcon },
  { path: '/nutrition', label: 'Nutrition', icon: NutritionIcon },
  { path: '/progress', label: 'Progress', icon: ProgressIcon },
  { path: '/settings', label: 'Settings', icon: SettingsIcon },
]

export default function MainLayout() {
  const { settings, loading } = useSettings()
  const navigate = useNavigate()
  const location = useLocation()

  useEffect(() => {
    if (!loading && !settings.onboarded) {
      navigate('/onboarding', { replace: true })
    }
  }, [loading, settings.onboarded])

  return (
    <div className="page-root">
      <Outlet />
      <nav className="bottom-nav">
        {NAV.map(({ path, label, icon: Icon }) => {
          const active = location.pathname === path
          return (
            <button key={path} className={`nav-item ${active ? 'active' : ''}`} onClick={() => navigate(path)}>
              <Icon />
              <span>{label}</span>
            </button>
          )
        })}
      </nav>
    </div>
  )
}

